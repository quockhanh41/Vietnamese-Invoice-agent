def _xml_path(corpus: pathlib.Path, record: dict[str, Any]) -> pathlib.Path:
    """`record["path"]` is always literally `"corpus/<file>"` — the generator
    hardcodes that prefix regardless of the `--out` directory it was actually
    written to (scripts/generate_invoices.py:529-532). Resolving against
    `corpus.parent` is the same trick `scripts/eval_classification.py::evaluate`
    already uses, and it is what makes this work both for the default
    `--corpus corpus` (relative to the repo root) and for a corpus generated
    into a pytest tmp_path (§2.1: `corpus/` itself is gitignored, so tests
    regenerate into a temp directory rather than assuming it is present)."""
    return corpus.parent / record["path"]


def _score_xml_extraction(corpus: pathlib.Path, xml_records: list[dict[str, Any]]) -> dict[str, Any]:
    field_total = 0
    field_match = 0
    parse_failures = 0
    for r in xml_records:
        try:
            invoice = parse_invoice_xml(_xml_path(corpus, r).read_bytes())
        except Exception:  # noqa: BLE001 - a parse failure is the metric, not a crash
            parse_failures += 1
            continue
        for f in XML_FIELDS:
            field_total += 1
            actual = getattr(invoice, f)
            if f == "total_amount":
                matched = Decimal(r[f]) == actual
            elif f == "issue_date":
                matched = date.fromisoformat(r[f]) == actual
            else:
                matched = r[f] == actual
            field_match += matched
    return {
        "field_total": field_total,
        "field_match": field_match,
        "field_rate": (field_match / field_total) if field_total else None,
        "parse_failures": parse_failures,
    }


def _score_validation(corpus: pathlib.Path, xml_records: list[dict[str, Any]]) -> dict[str, Any]:
    tp = fp = fn = 0
    for r in xml_records:
        try:
            invoice = parse_invoice_xml(_xml_path(corpus, r).read_bytes())
        except Exception:  # noqa: BLE001 - an unparsable record cannot be validated
            continue
        expected = set(r["expected_finding_codes"]) & VALIDATION_CODES
        actual = {f.code for f in validation.validate(invoice)} & VALIDATION_CODES
        tp += len(expected & actual)
        fp += len(actual - expected)
        fn += len(expected - actual)
    return {
        "tp": tp, "fp": fp, "fn": fn,
        "recall": (tp / (tp + fn)) if (tp + fn) else None,
    }


def _anomaly_key(r: dict[str, Any]) -> anomaly.InvoiceKey:
    return anomaly.InvoiceKey(
        seller_tax_code=r["seller_tax_code"],
        invoice_number=r["invoice_number"],
        issue_date=date.fromisoformat(r["issue_date"]),
        total_amount=Decimal(r["total_amount"]),
    )


def _vendor_stats_excluding(
    records: list[dict[str, Any]], tax_code: str, invoice_id: str
) -> anomaly.VendorStats:
    """Stats from the vendor's OTHER corpus invoices — mirrors what `signals`
    sees at run time (M4-D persists after the fan-out join), replicated here
    from the corpus alone so no DB is needed. Same recipe as
    tests/test_price_outlier_detection.py's `_stats_excluding`."""
    amounts = [
        Decimal(r["total_amount"]) for r in records
        if r["seller_tax_code"] == tax_code and r["invoice_id"] != invoice_id
    ]
    count = len(amounts)
    total = sum(amounts, Decimal(0))
    sum_sq = sum((a * a for a in amounts), Decimal(0))
    avg, stddev = derive(count, total, sum_sq)
    return anomaly.VendorStats(invoice_count=count, avg_amount=avg, stddev_amount=stddev)


def _score_anomaly(records: list[dict[str, Any]]) -> dict[str, Any]:
    """near_duplicate + price_outlier only — findings.CODE_REGISTRY's
    `raised_by='anomaly'` family, which is what design §10.4's Anomaly row
    means. NEW_VENDOR is excluded: severity `info`, reviewer context rather
    than an error claim (tests/test_price_outlier_detection.py::
    test_new_vendor_is_excluded_from_the_flag_false_positive_metric).
    DUPLICATE_INVOICE is excluded too: `raised_by='duplicate'`, a DB
    natural-key constraint, not a domain/anomaly.py signal.
    """
    by_id = {r["invoice_id"]: r for r in records}
    order = sorted(
        by_id,
        key=lambda iid: (
            by_id[iid]["issue_date"], by_id[iid]["invoice_series"], by_id[iid]["invoice_number"],
        ),
    )
    keys = {iid: _anomaly_key(by_id[iid]) for iid in by_id}

    nd_flagged: set[str] = set()
    for i, iid in enumerate(order):
        priors = [keys[o] for o in order[:i]]
        if anomaly.near_duplicate(keys[iid], priors) is not None:
            nd_flagged.add(iid)

    po_flagged = {
        r["invoice_id"] for r in records
        if anomaly.price_outlier(
            Decimal(r["total_amount"]),
            _vendor_stats_excluding(records, r["seller_tax_code"], r["invoice_id"]),
        )
        is not None
    }

    declared_nd = {r["invoice_id"] for r in records if "near_duplicate" in r["defects"]}
    declared_po = {r["invoice_id"] for r in records if "price_outlier" in r["defects"]}
    declared = declared_nd | declared_po
    flagged = nd_flagged | po_flagged

    fp = flagged - declared
    fp_attributed = fp - INJECTION_NEGATIVE_CONTROL_TWINS
    clean_n = len(records) - len(declared)

    return {
        "near_dup_recall": (
            len(nd_flagged & declared_nd) / len(declared_nd) if declared_nd else None
        ),
        "price_outlier_recall": (
            len(po_flagged & declared_po) / len(declared_po) if declared_po else None
        ),
        "total_n": len(records),
        "clean_n": clean_n,
        "fp_raw_ids": sorted(fp),
        "fp_attributed_ids": sorted(fp_attributed),
        "fp_raw_rate": (len(fp) / clean_n) if clean_n else None,
        "fp_attributed_rate": (len(fp_attributed) / clean_n) if clean_n else None,
    }


def _anomaly_footnote(stats: dict[str, Any]) -> str:
    twins = ", ".join(sorted(INJECTION_NEGATIVE_CONTROL_TWINS))
    residual = ", ".join(stats["fp_attributed_ids"]) or "none"
    return (
        "\n## Footnote — flag false-positive rate, both ways\n\n"
        f"Raw combined false-positive rate (near_duplicate + price_outlier vs. "
        f"`expected_finding_codes`, as-is): **{stats['fp_raw_rate']:.3%}** "
        f"({len(stats['fp_raw_ids'])} of {stats['clean_n']} clean invoices).\n\n"
        f"All {len(stats['fp_raw_ids']) - len(stats['fp_attributed_ids'])} of "
        f"near_duplicate's raw false positives are exactly the six "
        f"injection negative-control twins ({twins}) — `seed_injection`/"
        f"`strip_injection` (scripts/generator/defects.py) clone one base spec "
        f"per pair, so each twin shares `seller_tax_code`, `total_amount` and "
        f"`issue_date` with its carrier and differs only in `invoice_number`, "
        f"tripping `near_duplicate` at every window by construction (design "
        f"§9.1/§9.3; task-5-report.md). They are not evidence about "
        f"near_duplicate's calibration.\n\n"
        f"Attributing those six (excluded, not silently absorbed): "
        f"**{stats['fp_attributed_rate']:.3%}** "
        f"({len(stats['fp_attributed_ids'])} of {stats['clean_n']} clean invoices). "
        f"Residual false positives: {residual} (both `price_outlier` — "
        f"`anomaly.PRICE_OUTLIER_Z`/`PRICE_OUTLIER_MIN_INVOICES`'s own documented "
        f"floor, src/invoice_agent/domain/anomaly.py).\n\n"
        "Both numbers are reported because the raw rate is what a naive scorer "
        "publishes and reads worse than the detector's actual behaviour, while "
        "silently excluding the six would hide a real, if benign, corpus-"
        "construction artifact. The table above uses the RAW (more "
        "conservative) rate for its verdict.\n"
    )


def deterministic_rows(corpus: pathlib.Path) -> list[Row]:
    """The rows that need no LLM and therefore cost nothing to re-run.

    XML parse rate, seeded-error recall, and the flag false-positive rate —
    §10.4's headline metric, because it measures reviewer fatigue, which is what
    decides whether the system gets used at all.
    """
    records = manifest.read_manifest(corpus / "manifest.jsonl")
    xml_records = [r for r in records if r["source_type"] == "xml"]

    xml_stats = _score_xml_extraction(corpus, xml_records)
    val_stats = _score_validation(corpus, xml_records)
    ano_stats = _score_anomaly(records)

    anomaly_row = Row(
        stage="Anomaly (headline)",
        target=(
            "near_duplicate P/R = 1.0; price_outlier recall >= 0.90; "
            "combined flag false-positive rate <= 5% (raw; see footnote for "
            "the attributed rate excluding the 6 injection negative-control "
            "twins)"
        ),
        value=ano_stats["fp_raw_rate"],
        n=ano_stats["total_n"],
        method="deterministic",
        met=(
            verdict(ano_stats["near_dup_recall"], ">=", 1.0)
            and verdict(ano_stats["price_outlier_recall"], ">=", 0.90)
            and verdict(ano_stats["fp_raw_rate"], "<=", 0.05)
        ),
    )

    xml_row = Row(
        stage="XML extraction",
        target=(
            f"field exact match 100%, parse failures 0 "
            f"({xml_stats['field_total']} fields over {len(xml_records)} invoices)"
        ),
        value=xml_stats["field_rate"],
        n=len(xml_records),
        method="deterministic",
        met=(
            verdict(xml_stats["field_rate"], "==", 1.0)
            and verdict(xml_stats["parse_failures"], "==", 0)
        ),
    )

    vision_field_rate = VISION_FIELDS_MATCHED / VISION_FIELDS_TOTAL
    vision_amount_rate = VISION_TOTAL_AMOUNT_MATCHED / VISION_TOTAL_AMOUNT_N
    vision_row = Row(
        stage="Vision fallback",
        target=(
            "F1 >= 0.90 (proxy: field agreement rate); total_amount exact >= 0.85 "
            f"(N={VISION_TWINS_N} twins — small sample, see task-2-report.md)"
        ),
        value=vision_field_rate,
        n=VISION_TWINS_N,
        method="replay",
        met=(
            verdict(vision_field_rate, ">=", 0.90)
            and verdict(vision_amount_rate, ">=", 0.85)
        ),
        ci=wilson(VISION_TWINS_ALL_FIELDS_MATCHED, VISION_TWINS_N),
        underpowered=VISION_TWINS_N < UNDERPOWERED_N,
    )

    validation_row = Row(
        stage="Validation",
        target=(
            f"seeded-error recall 100%, false positives 0 "
            f"(FP: {val_stats['fp']} findings)"
        ),
        value=val_stats["recall"],
        n=len(xml_records),
        method="deterministic",
        met=(
            verdict(val_stats["recall"], "==", 1.0)
            and verdict(val_stats["fp"], "==", 0)
        ),
    )

    neg_ctrl_rate = NEGATIVE_CONTROL_MATCHES / NEGATIVE_CONTROL_N
    security_row = Row(
        stage="Security",
        target=(
            f"injection success 0/{INJECTION_SUCCESS_N}; negative control 100% "
            f"({NEGATIVE_CONTROL_MATCHES}/{NEGATIVE_CONTROL_N} classify identically — "
            f"2 measured category_laundering successes)"
        ),
        value=neg_ctrl_rate,
        n=NEGATIVE_CONTROL_N,
        method="replay",
        met=(
            verdict(float(INJECTION_SUCCESSES), "==", 0.0)
            and verdict(neg_ctrl_rate, ">=", 1.0)
        ),
    )

    hitl_rate = HITL_PASSES / HITL_RUNS_N
    hitl_row = Row(
        stage="HITL durability",
        target=f"interrupt -> kill -9 -> restart -> resume: {HITL_RUNS_N}/{HITL_RUNS_N}",
        value=hitl_rate,
        n=HITL_RUNS_N,
        method="live",
        met=verdict(hitl_rate, ">=", 1.0),
    )

    business_row = Row(
        stage="Business / STP",
        target="STP rate >= 85% (docs/notes/manual-baseline-protocol.md — stopwatch "
               "measurement, not a market-report figure)",
        value=None,
        n=0,
        method="pending",
        met=None,
    )

    return [
        anomaly_row, xml_row, vision_row, validation_row,
        security_row, hitl_row, business_row,
    ]


# ---------------------------------------------------------------------------
# Agent rows — Classification, Auditor, Cost. These need the pinned-rater
# artifact; `None` (no artifact) yields `unmeasured` rows rather than absent
# ones, per design §2.6/CLAUDE.md: a missing row is invisible, an unmeasured
# row is a question someone can act on.
# ---------------------------------------------------------------------------

_UNMEASURED_AGENT_ROWS = [
    Row(
        stage="Classification",
        target="accuracy >= 92% and beats keywords_vi baseline by >= 15 points "
               "(baseline shown beside the measured accuracy once available)",
        value=None, n=0, method="unmeasured", met=None,
    ),
    Row(
        stage="Auditor",
        target="override precision >= 0.60 (below 0.50 is net harmful)",
        value=None, n=0, method="unmeasured", met=None,
    ),
    Row(
        stage="Cost",
        target="shadow cost <= $0.01/invoice",
        value=None, n=0, method="unmeasured", met=None,
    ),
]


def agent_rows(artifact: dict[str, Any] | None) -> list[Row]:
    """Classification, Auditor and Cost, from the pinned-rater artifact.

    `None` (no artifact) yields unmeasured rows rather than absent ones: a
    missing row is invisible, an unmeasured row is a question someone can act on.
    """
    if artifact is None:
        return list(_UNMEASURED_AGENT_ROWS)

    baseline_acc = artifact["baseline"]["accuracy"]
    clf = artifact["classifier"]
    clf_acc = clf["accuracy"]
    gate_target = clf["gate_target"]
    classification_row = Row(
        stage="Classification",
        target=(
            f"accuracy >= 92% and beats keywords_vi baseline "
            f"(baseline accuracy = {baseline_acc:.1%}) by >= 15 points "
            f"(gate target = {gate_target:.1%})"
        ),
        value=clf_acc,
        n=clf["measured_n"],
        method="live",
        met=(
            verdict(clf_acc, ">=", 0.92)
            and verdict(clf_acc, ">=", gate_target)
        ),
    )

    # `override_ci`/`underpowered` are read with `[]`, not `.get()`: they are
    # always written by `eval_classification.precisions`, and a default would
    # silently drop the interval again the moment the artifact shape shifts.
    prec = artifact["precisions"]
    override_p = prec["override_precision"]
    lo, hi = prec["override_ci"]
    auditor_row = Row(
        stage="Auditor",
        target="override precision >= 0.60 (below 0.50 is net harmful)",
        value=override_p,
        n=prec["n"],
        method="live",
        met=verdict(override_p, ">=", 0.60),
        ci=(lo, hi),
        underpowered=prec["underpowered"],
    )

    cost = artifact["cost"]
    total_invoices = artifact["total_invoices"]
    shadow_per_invoice = (
        float(cost["total_shadow_cost_usd"]) / total_invoices if total_invoices else None
    )
    cost_row = Row(
        stage="Cost",
        target="shadow cost <= $0.01/invoice",
        value=shadow_per_invoice,
        n=total_invoices,
        method="live",
        met=verdict(shadow_per_invoice, "<=", 0.01),
    )

    return [classification_row, auditor_row, cost_row]


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate the eval report")
    parser.add_argument("--eval-json", type=pathlib.Path, default=None)
    parser.add_argument("--corpus", type=pathlib.Path, default=pathlib.Path("corpus"))
    parser.add_argument("--out", type=pathlib.Path, default=pathlib.Path("docs/eval-report.md"))
    args = parser.parse_args()

    artifact = (
        json.loads(args.eval_json.read_text(encoding="utf-8"))
        if args.eval_json and args.eval_json.exists()
        else None
    )
    det_rows = deterministic_rows(args.corpus)
    rows = det_rows + agent_rows(artifact)
    # `det_rows[0]` is always the Anomaly row (deterministic_rows puts it
    # first) — its footnote is appended after the table, not folded into a
    # column, so the raw-vs-attributed distinction reads as prose rather than
    # being squeezed into one table cell.
    records = manifest.read_manifest(args.corpus / "manifest.jsonl")
    footnote = _anomaly_footnote(_score_anomaly(records))
    args.out.write_text(render_report(rows) + footnote, encoding="utf-8")
    print(f"wrote {args.out} ({len(rows)} rows)")


if __name__ == "__main__":
    main()
